export function getInspirationById(id: string): InspirationImage | undefined {
  return inspirationImages.find((img) => img.id === id);
}

export function getInspirationByCategory(
  category: InspirationImage["category"]
): InspirationImage[] {
  return inspirationImages.filter((img) => img.category === category);
}

export function getInspirationByTag(tag: string): InspirationImage[] {
  return inspirationImages.filter((img) =>
    img.tags.some((t) => t.toLowerCase() === tag.toLowerCase())
  );
}

export function buildInspirationCatalogSummary(): string {
  const byCategory = {
    hairstyle: getInspirationByCategory("hairstyle"),
    color: getInspirationByCategory("color"),
    neighborhood: getInspirationByCategory("neighborhood"),
  };

  const lines: string[] = ["INSPIRATION IMAGE CATALOG:"];

  for (const [cat, images] of Object.entries(byCategory)) {
    lines.push(`\n[${cat.toUpperCase()}]`);
    for (const img of images) {
      lines.push(`  ${img.id}: "${img.alt}" (tags: ${img.tags.join(", ")})`);
    }
  }

  return lines.join("\n");
}
